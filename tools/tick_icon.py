"""Draw the green tick on the connected screen, as an A8 alpha mask.

Not a Figma export: there is no tick in the design file, and the first attempt
drew it with two LVGL line segments on the device. At this size that came out
hard-edged and lumpy - "looks like you've painted them with a potato" (Darren,
4 Nov 2026). LVGL's line drawing is not the right tool for a 20 px mark.

So it is rasterised here instead, the way tools/bolt_icon.py does the charging
bolt, and drawn as an image like every other icon on the dial: coverage from
the exact distance to the stroke, sampled 4x4 per pixel, with round caps and a
round join falling out of the distance field for free. The colour is applied
when it is drawn, so the one mask serves any colour.

Usage: python3 tools/tick_icon.py
"""
import math
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "ui" / "assets" / "img_tick.c"

# The mark itself, in pixels: down to the elbow, then up and across. The long
# arm is a little over twice the short one, which is what makes a tick read as
# a tick rather than as a bent line.
P = [(2.0, 9.6), (7.6, 15.2), (20.0, 2.0)]
HALF = 1.65   # half the stroke: 3.3 px, to sit beside 18 px text
SS = 4        # subsamples per pixel, each way
PAD = HALF + 0.6


def seg_dist(px, py, ax, ay, bx, by):
    vx, vy = bx - ax, by - ay
    wx, wy = px - ax, py - ay
    t = (wx * vx + wy * vy) / (vx * vx + vy * vy)
    t = 0.0 if t < 0.0 else 1.0 if t > 1.0 else t
    dx, dy = wx - t * vx, wy - t * vy
    return math.hypot(dx, dy)


def main():
    x0 = min(p[0] for p in P) - PAD
    y0 = min(p[1] for p in P) - PAD
    w = math.ceil(max(p[0] for p in P) + PAD - x0)
    h = math.ceil(max(p[1] for p in P) + PAD - y0)

    rows = []
    for y in range(h):
        row = []
        for x in range(w):
            acc = 0.0
            for sy in range(SS):
                for sx in range(SS):
                    px = x0 + x + (sx + 0.5) / SS
                    py = y0 + y + (sy + 0.5) / SS
                    d = min(seg_dist(px, py, *P[0], *P[1]), seg_dist(px, py, *P[1], *P[2]))
                    acc += 1.0 if d <= HALF else 0.0
            row.append(int(round(acc / (SS * SS) * 255.0)))
        rows.append(row)

    data = ",".join(str(v) for row in rows for v in row)
    OUT.write_text(
        "/* Generated by tools/tick_icon.py: the green tick on the connected screen. */\n"
        '#include "lvgl.h"\n\n'
        f"static const uint8_t data[] = {{{data}}};\n\n"
        "const lv_image_dsc_t img_tick = {\n"
        "    .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, "
        f".w = {w}, .h = {h}, .stride = {w}}},\n"
        "    .data_size = sizeof data,\n"
        "    .data = data,\n"
        "};\n")
    print(f"{OUT}: {w}x{h}")


if __name__ == "__main__":
    main()
