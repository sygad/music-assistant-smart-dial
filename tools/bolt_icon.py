"""Draw the charging bolt for the Settings battery into ui/assets/img_bolt.c.

The other icons come from Figma (tools/png_to_c.py); the battery and its bolt
were asked for after the design (Darren, 28 Oct 2026), so the bolt is drawn
here instead: the usual lightning shape, filled at 8x and scaled down for a
clean edge, as an A8 alpha mask the UI draws in whatever colour it needs.

Usage: python3 tools/bolt_icon.py
"""
from pathlib import Path

from PIL import Image, ImageDraw

W, H, SS = 10, 13, 8  # the size on screen, and how far it's oversampled
SHAPE = [(0.70, 0.00), (0.04, 0.60), (0.40, 0.60), (0.30, 1.00), (0.96, 0.40), (0.60, 0.40)]
OUT = Path(__file__).resolve().parent.parent / "ui" / "assets" / "img_bolt.c"

big = Image.new("L", (W * SS, H * SS), 0)
ImageDraw.Draw(big).polygon([(x * (W * SS - 1), y * (H * SS - 1)) for x, y in SHAPE], fill=255)
alpha = big.resize((W, H), Image.LANCZOS)

rows = [",".join(str(alpha.getpixel((x, y))) for x in range(W)) for y in range(H)]
OUT.write_text(
    "/* Generated by tools/bolt_icon.py: the charging bolt in the Settings battery. */\n"
    '#include "lvgl.h"\n\n'
    "static const uint8_t data[] = {\n    " + ",\n    ".join(rows) + "};\n\n"
    "const lv_image_dsc_t img_bolt = {\n"
    "    .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, "
    f".w = {W}, .h = {H}, .stride = {W}}},\n"
    "    .data_size = sizeof data,\n"
    "    .data = data,\n"
    "};\n")
print(f"Wrote {OUT}")
