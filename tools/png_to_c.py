"""Turn Figma PNG exports (assets/figma/) into LVGL image data (ui/assets/).

Single-colour icons become A8 alpha masks (the colour is applied when drawn).
Exported from Figma file jAaJDrPIrLTzMMPcqeqG4U at scale 1, so each image is
exactly its size in the 360x360 design.

The exports come out opaque, on the frame's #F5F5F5 background, so the alpha
is worked out from the colour: how far each pixel has moved from the background
towards the icon's own colour. The back button's arrow is white on its pill
(#5B5B5B at 80% = #797979 on that background); the pill itself is drawn by LVGL.

Usage: python3 tools/png_to_c.py
"""
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "figma"
OUT = ROOT / "ui" / "assets"

# name: (format, Figma node)
IMAGES = {
    "treble": ("A8", "559:255, EQ base; 559:360 in focus"),
    "bass": ("A8", "559:254"),
    "subs": ("A8", "559:256"),
    "trident": ("A8", "559:257"),
    "back": ("ARROW", "559:361, EQ focus back button: the arrow only"),
}


def read_png(path):
    data = path.read_bytes()
    assert data[:8] == b"\x89PNG\r\n\x1a\n"
    pos, idat, w = 8, b"", 0
    while pos < len(data):
        n, kind = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + n]
        if kind == b"IHDR":
            w, h, depth, ctype, _, _, interlace = struct.unpack(">IIBBBBB", body)
            assert depth == 8 and ctype == 6 and interlace == 0, "expects 8-bit RGBA, not interlaced"
        elif kind == b"IDAT":
            idat += body
        pos += 12 + n
    raw = zlib.decompress(idat)
    stride, rows, prev = w * 4, [], bytearray(w * 4)
    for y in range(h):
        f, line = raw[y * (stride + 1)], bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for i in range(stride):
            a = line[i - 4] if i >= 4 else 0
            b = prev[i]
            c = prev[i - 4] if i >= 4 else 0
            if f == 1: line[i] = (line[i] + a) & 255
            elif f == 2: line[i] = (line[i] + b) & 255
            elif f == 3: line[i] = (line[i] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append(bytes(line))
        prev = line
    return w, h, rows


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    decls = []
    for name, (fmt, node) in IMAGES.items():
        w, h, rows = read_png(SRC / f"{name}.png")
        if fmt == "A8":
            bg = rows[0][:3]
            far = lambda r, x: sum(abs(r[x * 4 + i] - bg[i]) for i in range(3))
            full = max(far(r, x) for r in rows for x in range(w))
            px = bytes(min(255, round(far(r, x) * 255 / full)) for r in rows for x in range(w))
        else:  # the white arrow on the pill; outside the pill's straight middle is all pill edge
            px = bytes(min(255, max(0, round((r[x * 4] - 121) * 255 / (255 - 121))))
                       if h // 2 <= x < w - h // 2 and 4 <= y < h - 4 else 0
                       for y, r in enumerate(rows) for x in range(w))
        stride, cf = w, "LV_COLOR_FORMAT_A8"
        body = ",".join(str(b) for b in px)
        (OUT / f"img_{name}.c").write_text(
            f"/* Generated by tools/png_to_c.py from assets/figma/{name}.png (Figma node {node}). */\n"
            '#include "lvgl.h"\n\n'
            f"static const uint8_t data[] = {{{body}}};\n\n"
            f"const lv_image_dsc_t img_{name} = {{\n"
            f"    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = {cf}, .w = {w}, .h = {h}, .stride = {stride}}},\n"
            f"    .data_size = sizeof data,\n    .data = data,\n}};\n")
        decls.append(f"LV_IMAGE_DECLARE(img_{name}); /* {w}x{h} {fmt} */")
        print(f"img_{name}: {w}x{h} {fmt}")
    (OUT / "assets.h").write_text("/* Generated by tools/png_to_c.py. */\n#pragma once\n#include \"lvgl.h\"\n\n" + "\n".join(decls) + "\n")


if __name__ == "__main__":
    main()
